    "           count(*) FILTER (WHERE label='true_positive'  AND similarity< th)",
    "    INTO tp, fp, fn",
    "    FROM alerts WHERE suspect_id = p_suspect_id;",
    "    IF tp + fp = 0 OR tp + fn = 0 THEN CONTINUE; END IF;",
    "    pr := tp::float / (tp + fp);",
    "    re := tp::float / (tp + fn);",
    "    IF pr + re = 0 THEN CONTINUE; END IF;",
    "    f1 := 2 * pr * re / (pr + re);",
    "    IF f1 > best_f1 THEN best_f1 := f1; best_th := th; END IF;",
    "  END LOOP;",
    "  RETURN best_th;",
    "END $$;",

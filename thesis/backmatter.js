    "RETURNS double precision LANGUAGE plpgsql STABLE AS $$",
    "DECLARE",
    "  best_th double precision := 0.45;",
    "  best_f1 double precision := 0.0;",
    "  th  double precision;",
    "  tp  int;",
    "  fp  int;",
    "  fn  int;",
    "  pr  double precision;",
    "  re  double precision;",

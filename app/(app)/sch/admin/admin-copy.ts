export function schAdminCopy(lang: Lang): SchAdminCopy {
  return { mn, en, kr }[lang];
}

export function schStatusLabel(status: SchStatus, lang: Lang): string {
  return schAdminCopy(lang)[status];
}

export function schStatusVariant(status: SchStatus): "accent" | "success" | "warning" | "danger" | "info" | "muted" {
  switch (status) {
    case "paid": return "success";
    case "pending": return "warning";
    case "waitlist": return "info";
    case "rejected": return "danger";
    default: return "muted";
  }
}

/** Tiny `{name}` interpolation for the copy strings above. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (key in vars ? String(vars[key]) : `{${key}}`));
}
